    <h1>How Campus Lost &amp; Found works</h1>
    <p class="lead">Everything here follows one idea: a lost item goes from a <strong>listing</strong> to a <strong>claim</strong> to a <strong>handover</strong>.</p>

    <ol class="steps-list">
        <li><strong>Listing</strong><span>Someone reports a lost or found item. Found items are public so owners can find them.</span></li>
        <li><strong>Claim</strong><span>The owner submits a claim describing details only they would know. A custodian reviews it.</span></li>
        <li><strong>Handover</strong><span>If approved, a custodian arranges a pickup. The owner shows student ID and collects the item.</span></li>
    </ol>

    <h2 id="faq">Common questions</h2>

    <details class="faq"><summary>Why can't I post or claim yet?</summary>
        <div><p>You need to verify your university email first. Use the banner at the top of any page to send a new link.</p></div></details>
    <details class="faq"><summary>What should I write in a claim?</summary>
        <div><p>Contents, marks, stickers, serial numbers or anything a stranger could not guess. You can attach a receipt or photo as private proof.</p></div></details>
    <details class="faq"><summary>Who can see my contact details?</summary>
        <div><p>No one on public pages. Use Messages to talk to a poster or claimant without sharing your phone or email.</p></div></details>
    <details class="faq"><summary>My claim is "under review". What now?</summary>
        <div><p>A custodian is comparing your statement with the finder's private detail. You will get an alert when there is a decision.</p></div></details>
    <details class="faq"><summary>My claim was approved. What next?</summary>
        <div><p>A custodian arranges the handover. Bring your student ID. Handover is only completed after the ID is checked.</p></div></details>
    <details class="faq"><summary>Can I change or delete a listing?</summary>
        <div><p>You can edit a listing while it is still open. Open "My listings" to manage yours.</p></div></details>
    <details class="faq"><summary>Someone posted something inappropriate.</summary>
        <div><p>Use "Report this listing" on the item page. An administrator will review it.</p></div></details>

